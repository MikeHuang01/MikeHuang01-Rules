#!/usr/bin/env python3
"""Generate the 直连 (Direct) resources from the blackmatrix7 upstream list.

Layout produced here:

    QuantumultX/Direct.list     具体域名直连（HOST / HOST-SUFFIX / HOST-KEYWORD ...）
    QuantumultX/DirectGeo.list  兜底直连（内网网段 / GEOIP / IP-ASN）

The two files are split on purpose. QuantumultX matches rules in the order the
resources are listed, so the concrete 直连 rules must be evaluated *before*
AdBlock (otherwise a broad ``HOST-SUFFIX,...,REJECT`` swallows them) while the
``geoip, cn`` fallback must stay *after* AdBlock (otherwise every mainland
domain would be direct and ad blocking would stop working).
"""
from __future__ import annotations

import sys

from rulelib import (
    IP_TYPES,
    NETWORK_TYPES,
    QX_DIR,
    SR_DIR,
    Rule,
    dedupe,
    fetch,
    parse_rules,
    write_if_changed,
)

UPSTREAM = (
    "https://raw.githubusercontent.com/blackmatrix7/ios_rule_script/master/"
    "rule/QuantumultX/Direct/Direct.list"
)
CUSTOM = QX_DIR / "CustomDirect.list"

# ad.12306.cn is rejected by AdBlock; keep its DIRECT route from bypassing that.
SUPPRESSED = {("HOST", "ad.12306.cn")}


def qx_header(title: str, extra) -> list[str]:
    return [
        f"# NAME: {title}",
        "# AUTHOR: blackmatrix7",
        "# REPO: https://github.com/blackmatrix7/ios_rule_script",
        "# MAINTAINER: MikeHuang01",
        "# AUTO-GENERATED: do not edit this file by hand",
        "# CUSTOM SOURCE: QuantumultX/CustomDirect.list",
        f"# UPSTREAM: {UPSTREAM}",
        *extra,
        "# 去重键：规则类型 + 匹配值（不区分大小写）",
        "",
    ]


def sr_header(title: str, extra) -> list[str]:
    return [
        f"# NAME: {title}",
        "# AUTHOR: blackmatrix7",
        "# REPO: https://github.com/blackmatrix7/ios_rule_script",
        "# MAINTAINER: MikeHuang01",
        "# AUTO-GENERATED: do not edit this file by hand",
        *extra,
        "",
    ]


def build_text(header: list[str], rules: list[Rule]) -> str:
    return "\n".join(header + [rule.text for rule in rules]) + "\n"


def main() -> int:
    if not CUSTOM.is_file():
        raise FileNotFoundError(f"Missing custom rules: {CUSTOM}")

    custom_rules = parse_rules(CUSTOM.read_text(encoding="utf-8").splitlines())
    upstream_rules = parse_rules(fetch(UPSTREAM).splitlines())

    # Local rules first so a custom value always wins over an upstream duplicate.
    merged = [
        rule
        for rule in dedupe(custom_rules + upstream_rules)
        if rule.key not in SUPPRESSED
    ]

    # Policy names are case-insensitive in both clients; normalise them so the
    # generated files stay diff-friendly (hand-written rules may use any case).
    network = [rule.with_policy("direct") for rule in merged if rule.rule_type in NETWORK_TYPES]
    geo = [rule.with_policy("direct") for rule in merged if rule.rule_type in IP_TYPES]
    unknown = [rule for rule in merged if rule.rule_type not in NETWORK_TYPES | IP_TYPES]
    if unknown:
        raise ValueError(f"Unexpected rule type(s): {[rule.text for rule in unknown[:5]]}")
    if len(network) + len(geo) != len(merged):
        raise ValueError("Rule split lost entries")

    write_if_changed(
        QX_DIR / "Direct.list",
        build_text(
            qx_header(
                "Direct",
                [
                    "# 用途：具体域名直连。请排在 AdBlock 之前。",
                    f"# TOTAL: {len(network)}",
                ],
            ),
            network,
        ),
    )
    write_if_changed(
        QX_DIR / "DirectGeo.list",
        build_text(
            qx_header(
                "DirectGeo",
                [
                    "# 用途：兜底直连（内网网段 / GEOIP / IP-ASN）。请排在 AdBlock 之后。",
                    f"# TOTAL: {len(geo)}",
                ],
            ),
            geo,
        ),
    )

    sr_network = [rule.shadowrocket().with_policy("DIRECT") for rule in network]
    sr_geo = [rule.shadowrocket().with_policy("DIRECT") for rule in geo]
    write_if_changed(
        SR_DIR / "Direct.conf",
        build_text(
            sr_header(
                "Direct",
                [
                    "# SOURCE: QuantumultX/Direct.list",
                    "# 用途：具体域名直连。请排在 AdBlock 之前。",
                    f"# TOTAL: {len(sr_network)}",
                ],
            ),
            sr_network,
        ),
    )
    write_if_changed(
        SR_DIR / "DirectGeo.conf",
        build_text(
            sr_header(
                "DirectGeo",
                [
                    "# SOURCE: QuantumultX/DirectGeo.list",
                    "# 用途：兜底直连。请排在 AdBlock 之后。",
                    f"# TOTAL: {len(sr_geo)}",
                ],
            ),
            sr_geo,
        ),
    )

    print(
        f"direct custom={len(custom_rules)} network={len(network)} geo={len(geo)} "
        f"superseded={len(custom_rules) + len(upstream_rules) - len(merged)}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
