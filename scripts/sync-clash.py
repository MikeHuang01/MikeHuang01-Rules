#!/usr/bin/env python3
"""Generate the Clash (mihomo) rule providers from the QuantumultX resources.

    QuantumultX/Direct.list     ->  Clash/Direct.yaml
    QuantumultX/AdBlock.list    ->  Clash/AdBlock.yaml
    QuantumultX/DirectGeo.list  ->  Clash/DirectGeo.yaml

Clash is the third client, and it differs from QuantumultX / Shadowrocket in one
structural way: a rule-provider never carries the action. It only supplies match
conditions, and the action comes from the RULE-SET,<name>,<policy> line in the
configuration that references it. The generated files therefore contain
type,value pairs only -- no direct / REJECT column.

The ordering contract is identical to QuantumultX (see README):

    RULE-SET,direct  ->  RULE-SET,adblock  ->  RULE-SET,directgeo

Clash is evaluated top-down exactly like QX, so the same three-layer split that
keeps fairplay.l.qq.com direct while rejecting the rest of l.qq.com holds here.
"""
from __future__ import annotations

import sys

from rulelib import (
    CLASH_DIR,
    QX_DIR,
    Rule,
    dedupe,
    drop_shadowed,
    parse_rules,
    to_clash,
    write_if_changed,
)

SOURCES = (
    ("Direct.yaml", "Direct.list", "Direct", "具体域名直连。必须排在去广告之前。"),
    ("AdBlock.yaml", "AdBlock.list", "AdBlock", "去广告与劫持拦截。排在具体直连之后、兜底直连之前。"),
    ("DirectGeo.yaml", "DirectGeo.list", "DirectGeo", "兜底直连（内网网段 / IP-ASN / GEOIP）。必须排在最后。"),
)


def build(source: str, title: str, purpose: str):
    path = QX_DIR / source
    if not path.is_file():
        raise FileNotFoundError(f"Missing source resource: {path}")

    parsed = parse_rules(path.read_text(encoding="utf-8").splitlines())
    converted: list[Rule] = []
    unsupported: list[str] = []
    for rule in parsed:
        clash_rule = to_clash(rule)
        if clash_rule is None:
            unsupported.append(rule.text)
            continue
        rule_type, value = clash_rule
        converted.append(Rule(rule_type, value, ""))

    deduped = dedupe(converted)
    kept, shadowed = drop_shadowed(deduped)

    lines = [
        f"# NAME: {title}",
        "# AUTHOR: blackmatrix7",
        "# REPO: https://github.com/blackmatrix7/ios_rule_script",
        "# MAINTAINER: MikeHuang01",
        "# AUTO-GENERATED: do not edit this file by hand",
        f"# SOURCE: QuantumultX/{source}",
        f"# TOTAL: {len(kept)}",
        f"# 用途：{purpose}",
        "# Clash 规则提供器格式：behavior=classical，payload 只含匹配条件、不含策略。",
        "# 策略由配置里的 RULE-SET 行决定，见 Clash/README.md。",
    ]
    if unsupported:
        types = ", ".join(sorted({item.split(",")[0] for item in unsupported}))
        lines.append(f"# 已省略 {len(unsupported)} 条 Clash 无法表达的规则（{types}）")
    lines.append("")
    lines.append("payload:")
    lines.extend("  - '%s,%s'" % (rule.rule_type, rule.value) for rule in kept)
    return "\n".join(lines) + "\n", len(parsed), len(kept), len(shadowed), unsupported


def main() -> int:
    report = []
    for filename, source, title, purpose in SOURCES:
        text, source_count, total, shadowed, unsupported = build(source, title, purpose)
        write_if_changed(CLASH_DIR / filename, text)
        report.append((filename, source_count, total, shadowed, len(unsupported)))

    print("clash providers generated from QuantumultX resources:")
    for filename, source_count, total, shadowed, unsupported in report:
        print(
            f"  {filename:<16} source={source_count:<7} payload={total:<7} "
            f"shadowed={shadowed:<3} unsupported={unsupported}"
        )
        if source_count != total + shadowed + unsupported:
            raise ValueError(f"{filename}: rule count mismatch")
    return 0


if __name__ == "__main__":
    sys.exit(main())
