#!/usr/bin/env python3
"""Generate the 去广告 (AdBlock) resources from the blackmatrix7 upstream lists.

    QuantumultX/AdBlock.list   QuantumultX 分流资源（REJECT）
    Shadowrocket/AdBlock.conf  Shadowrocket 规则集（DOMAIN / REJECT）

Both files are rebuilt from upstream Advertising + Hijacking on every run, so the
291k rule snapshot in this repository can no longer drift away from upstream.

Ordering contract with the Direct resources (see README):

    Direct.list  ->  AdBlock.list  ->  DirectGeo.list

Because Direct.list is evaluated first, a concrete 直连 rule such as
``fairplay.l.qq.com`` wins over a broad ``HOST-SUFFIX,l.qq.com,REJECT``, while
every other ``l.qq.com`` host is still rejected. The checker below reports how
many Direct rules rely on that ordering, so a future reordering of the
resources shows up as a reviewable number instead of a silent breakage.
"""
from __future__ import annotations

import sys

from rulelib import (
    QX_DIR,
    SR_DIR,
    Rule,
    covered_by,
    dedupe,
    drop_shadowed,
    fetch,
    parse_rule,
    parse_rules,
    write_if_changed,
)

UPSTREAMS = (
    "https://raw.githubusercontent.com/blackmatrix7/ios_rule_script/master/"
    "rule/QuantumultX/Advertising/Advertising.list",
    "https://raw.githubusercontent.com/blackmatrix7/ios_rule_script/master/"
    "rule/QuantumultX/Hijacking/Hijacking.list",
)
ALLOWED_TYPES = {"HOST", "HOST-SUFFIX", "HOST-KEYWORD", "IP-CIDR", "IP6-CIDR"}


def load_upstream() -> list[Rule]:
    rules: list[Rule] = []
    for url in UPSTREAMS:
        rules.extend(parse_rules(fetch(url).splitlines()))
    return rules


def main() -> int:
    upstream = load_upstream()

    rejected: list[Rule] = []
    for rule in upstream:
        if rule.rule_type not in ALLOWED_TYPES:
            continue
        rejected.append(rule.with_policy("REJECT", add_no_resolve=True))
    # HOST,x next to HOST-SUFFIX,x is duplication, not a second rule.
    merged, shadowed_rules = drop_shadowed(dedupe(rejected))

    qx_lines = [
        "# NAME: AdBlock",
        "# AUTHOR: blackmatrix7",
        "# REPO: https://github.com/blackmatrix7/ios_rule_script",
        "# MAINTAINER: MikeHuang01",
        "# AUTO-GENERATED: do not edit this file by hand",
        f"# UPSTREAM: {UPSTREAMS[0]}",
        f"# UPSTREAM: {UPSTREAMS[1]}",
        f"# TOTAL: {len(merged)}",
        "# 用途：去广告与劫持拦截，动作统一 REJECT；IP 网段附带 no-resolve。",
        "# 顺序：Direct.list -> AdBlock.list -> DirectGeo.list，具体直连规则优先。",
        "",
    ]
    sr_lines = [
        "# NAME: AdBlock",
        "# AUTHOR: blackmatrix7",
        "# REPO: https://github.com/blackmatrix7/ios_rule_script",
        "# MAINTAINER: MikeHuang01",
        "# AUTO-GENERATED: do not edit this file by hand",
        "# SOURCE: QuantumultX/AdBlock.list",
        f"# TOTAL: {len(merged)}",
        "# 用途：去广告与劫持拦截，动作统一 REJECT；DOMAIN 语法，IP 网段附带 no-resolve。",
        "",
    ]

    write_if_changed(
        QX_DIR / "AdBlock.list",
        "\n".join(qx_lines + [rule.text for rule in merged]) + "\n",
    )
    write_if_changed(
        SR_DIR / "AdBlock.conf",
        "\n".join(sr_lines + [rule.shadowrocket().text for rule in merged]) + "\n",
    )

    # Reviewable ordering report: these Direct rules are only direct because
    # Direct.list is evaluated before AdBlock.list.
    direct_file = QX_DIR / "Direct.list"
    shadowed = 0
    examples = []
    if direct_file.is_file():
        suffix_rules = [r for r in merged if r.rule_type in {"HOST-SUFFIX", "HOST-KEYWORD", "HOST"}]
        index = {}
        for rule in suffix_rules:
            index.setdefault(rule.rule_type, []).append(rule)
        for line in direct_file.read_text(encoding="utf-8").splitlines():
            rule = parse_rule(line)
            if rule is None or rule.rule_type not in {"HOST", "HOST-SUFFIX", "HOST-KEYWORD"}:
                continue
            host = rule.value.lower()
            for candidate in suffix_rules:
                if candidate.value.lower() == host and candidate.rule_type == "HOST":
                    continue
                if covered_by(host, candidate):
                    shadowed += 1
                    if len(examples) < 5:
                        examples.append(f"{rule.text}  <-  {candidate.text}")
                    break

    print(
        f"adblock upstream={len(upstream)} kept={len(merged)} "
        f"dropped_types={len(upstream) - len(rejected)} shadowed={len(shadowed_rules)}"
    )
    for rule in shadowed_rules:
        print(f"  pruned duplicate: {rule.text}")
    print(f"direct rules protected by ordering: {shadowed}")
    for example in examples:
        print(f"  {example}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
