#!/usr/bin/env python3
"""Generate the custom proxy (ProxyLocal) resources from CustomProxy.list.

    QuantumultX/CustomProxy.list    手写维护（唯一入口）
    QuantumultX/ProxyLocal.list     自动生成  策略 proxy
    Shadowrocket/ProxyLocal.conf    自动生成  策略 PROXY
    Clash/ProxyLocal.yaml           自动生成  Clash 规则提供器（不含策略）

Ordering contract (see README): this layer sits AFTER AdBlock and BEFORE
ChinaMax / Apple / Global. A broad rule such as host-keyword,github,proxy must
not shadow the GitHub telemetry hosts that AdBlock rejects.
"""
from __future__ import annotations

import sys

from rulelib import (
    CLASH_DIR,
    NETWORK_TYPES,
    QX_DIR,
    SR_DIR,
    dedupe,
    drop_shadowed,
    parse_rules,
    to_clash,
    write_if_changed,
)

CUSTOM = QX_DIR / "CustomProxy.list"
QX_POLICY = "proxy"
SR_POLICY = "PROXY"


def build_text(header, lines):
    return "\n".join(header + lines) + "\n"


def main() -> int:
    if not CUSTOM.is_file():
        raise FileNotFoundError(f"Missing custom rules: {CUSTOM}")

    rules = parse_rules(CUSTOM.read_text(encoding="utf-8").splitlines())
    unknown = [rule for rule in rules if rule.rule_type not in NETWORK_TYPES]
    if unknown:
        raise ValueError(
            "CustomProxy.list only accepts network rules, got: "
            + str([rule.text for rule in unknown[:5]])
        )

    merged, shadowed = drop_shadowed(dedupe(rules))
    qx_rules = [rule.with_policy(QX_POLICY) for rule in merged]
    sr_rules = [rule.shadowrocket().with_policy(SR_POLICY) for rule in merged]

    write_if_changed(
        QX_DIR / "ProxyLocal.list",
        build_text(
            [
                "# NAME: ProxyLocal",
                "# AUTHOR: MikeHuang01",
                "# MAINTAINER: MikeHuang01",
                "# AUTO-GENERATED: do not edit this file by hand",
                "# CUSTOM SOURCE: QuantumultX/CustomProxy.list",
                f"# TOTAL: {len(qx_rules)}",
                "# 用途：自定义代理（github 关键词 / DNS Leak）。请排在「去广告」之后、国内/全球大表之前。",
                "# 去重键：规则类型 + 匹配值（不区分大小写）",
                "",
            ],
            [rule.text for rule in qx_rules],
        ),
    )
    write_if_changed(
        SR_DIR / "ProxyLocal.conf",
        build_text(
            [
                "# NAME: ProxyLocal",
                "# AUTHOR: MikeHuang01",
                "# MAINTAINER: MikeHuang01",
                "# AUTO-GENERATED: do not edit this file by hand",
                "# SOURCE: QuantumultX/ProxyLocal.list",
                f"# TOTAL: {len(sr_rules)}",
                "# 用途：自定义代理。请排在 AdBlock 之后、国内 / 全局 之前。",
                "",
            ],
            [rule.text for rule in sr_rules],
        ),
    )

    clash_entries = []
    for rule in merged:
        converted = to_clash(rule)
        if converted is None:
            continue
        clash_entries.append(converted)
    write_if_changed(
        CLASH_DIR / "ProxyLocal.yaml",
        build_text(
            [
                "# NAME: ProxyLocal",
                "# AUTHOR: MikeHuang01",
                "# MAINTAINER: MikeHuang01",
                "# AUTO-GENERATED: do not edit this file by hand",
                "# SOURCE: QuantumultX/ProxyLocal.list",
                f"# TOTAL: {len(clash_entries)}",
                "# 用途：自定义代理层。Clash 侧 RULE-SET 必须排在 adblock 之后。",
                "# Clash 规则提供器格式：behavior=classical，payload 只含匹配条件、不含策略。",
                "payload:",
            ],
            ["  - '" + rule_type + "," + value + "'" for rule_type, value in clash_entries],
        ),
    )

    print(f"proxylocal input={len(rules)} kept={len(merged)} shadowed={len(shadowed)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
