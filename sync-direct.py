#!/usr/bin/env python3
"""Merge MikeHuang01 custom rules with the live blackmatrix7 Direct list.

The generated files are intentionally committed: QuantumultX and Shadowrocket
can fetch them directly from raw.githubusercontent.com. Custom rules are never
overwritten by this script.
"""
from __future__ import annotations

import os
import re
import sys
import tempfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CUSTOM = ROOT / "QuantumultX" / "CustomDirect.list"
QX_OUT = ROOT / "QuantumultX" / "Direct.list"
SR_OUT = ROOT / "Shadowrocket" / "Direct.conf"
UPSTREAM = "https://raw.githubusercontent.com/blackmatrix7/ios_rule_script/master/rule/QuantumultX/Direct/Direct.list"

TYPE_MAP = {
    "HOST": "DOMAIN",
    "HOST-SUFFIX": "DOMAIN-SUFFIX",
    "HOST-KEYWORD": "DOMAIN-KEYWORD",
}


def key(line: str) -> tuple[str, str] | None:
    parts = [p.strip() for p in line.split(",")]
    if len(parts) < 3 or not parts[0] or parts[0].startswith("#"):
        return None
    rule_type = parts[0].upper()
    if rule_type in TYPE_MAP:
        rule_type = TYPE_MAP[rule_type]
    return rule_type, parts[1].lower()


def normalize(lines: list[str]) -> list[str]:
    seen: set[tuple[str, str]] = set()
    result: list[str] = []
    for raw in lines:
        line = raw.strip()
        k = key(line)
        if k is None or k in seen:
            continue
        seen.add(k)
        result.append(line)
    return result


def shadowrocket(line: str) -> str:
    parts = [p.strip() for p in line.split(",")]
    rule_type = parts[0].upper()
    rule_type = TYPE_MAP.get(rule_type, rule_type)
    if rule_type in {"IP-CIDR", "IP6-CIDR"}:
        return f"{rule_type},{parts[1]},{parts[2]},no-resolve"
    return f"{rule_type},{parts[1]},{parts[2]}"


def main() -> int:
    if not CUSTOM.exists():
        raise FileNotFoundError(f"Missing custom rules: {CUSTOM}")
    custom = [line for line in CUSTOM.read_text(encoding="utf-8").splitlines() if line.strip()]
    request = urllib.request.Request(UPSTREAM, headers={"User-Agent": "MikeHuang01-Rules-sync/1.0"})
    with urllib.request.urlopen(request, timeout=60) as response:
        upstream = response.read().decode("utf-8").splitlines()
    custom_rules = [line for line in custom if key(line)]
    upstream_rules = [line.strip() for line in upstream if key(line)]
    merged = normalize(custom_rules + upstream_rules)

    qx_header = [
        "# NAME: Direct",
        "# AUTHOR: blackmatrix7",
        "# REPO: https://github.com/blackmatrix7/ios_rule_script",
        "# MAINTAINER: MikeHuang01",
        "# AUTO-GENERATED: do not edit this file by hand",
        "# CUSTOM SOURCE: QuantumultX/CustomDirect.list",
        f"# UPSTREAM: {UPSTREAM}",
        f"# TOTAL: {len(merged)}",
        "# 去重键：规则类型 + 匹配值（不区分大小写）",
        "",
    ]
    qx_text = "\n".join(qx_header + merged) + "\n"
    sr_lines = [shadowrocket(line) for line in merged]
    sr_header = [
        "# NAME: Direct",
        "# AUTHOR: blackmatrix7",
        "# REPO: https://github.com/blackmatrix7/ios_rule_script",
        "# MAINTAINER: MikeHuang01",
        "# AUTO-GENERATED: do not edit this file by hand",
        "# SOURCE: QuantumultX/Direct.list",
        f"# TOTAL: {len(merged)}",
        "# HOST 已转换为 DOMAIN；IP-CIDR 已附加 no-resolve。",
        "",
    ]
    sr_text = "\n".join(sr_header + sr_lines) + "\n"

    for path, text in ((QX_OUT, qx_text), (SR_OUT, sr_text)):
        path.parent.mkdir(parents=True, exist_ok=True)
        if path.exists() and path.read_text(encoding="utf-8") == text:
            print(f"unchanged: {path.relative_to(ROOT)}")
            continue
        with tempfile.NamedTemporaryFile("w", encoding="utf-8", newline="\n", dir=path.parent, delete=False) as tmp:
            tmp.write(text)
            temp_name = tmp.name
        os.replace(temp_name, path)
        print(f"updated: {path.relative_to(ROOT)}")
    print(f"custom={len(custom_rules)} total={len(merged)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
